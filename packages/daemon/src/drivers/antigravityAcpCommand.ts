import { createHash } from "node:crypto";
import { chmodSync, closeSync, existsSync, mkdirSync, openSync, readSync, renameSync, statSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { resolveRaftHome } from "../raftHome";

const WRAPPER_INSPECT_BYTES = 4096;

/**
 * Detect a POSIX shell wrapper that launches `agy` through an alternate glibc
 * loader (e.g. `ld-linux-x86-64.so.2 ... agy.orig "$@"` on older glibc hosts).
 * On such hosts `/proc/self/exe` resolves to the dynamic linker rather than the
 * wrapper script, so `agy acp --process-per-session` crashes when spawning its
 * `--worker` subprocess (`write |1: broken pipe`).
 */
export function isGlibcLoaderWrapperScript(
  commandPath: string,
  platform: NodeJS.Platform = process.platform,
): boolean {
  if (platform === "win32" || !commandPath) return false;
  try {
    const stat = statSync(commandPath);
    if (!stat.isFile()) return false;
    const fd = openSync(commandPath, "r");
    try {
      const buffer = Buffer.alloc(Math.min(stat.size, WRAPPER_INSPECT_BYTES));
      const bytesRead = readSync(fd, buffer, 0, buffer.length, 0);
      if (bytesRead < 2) return false;
      const head = buffer.subarray(0, bytesRead).toString("utf8");
      return head.startsWith("#!") && /\bld-linux(?:-[a-z0-9_-]+)?\.so\.\d+/i.test(head);
    } finally {
      closeSync(fd);
    }
  } catch {
    return false;
  }
}

function shellQuote(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

function buildAcpShimScript(targetCommand: string): string {
  return [
    "#!/bin/sh",
    "# Generated by Raft daemon for glibc-wrapped agy: filter --process-per-session",
    "# so ACP runs in-process instead of re-execing ld-linux via /proc/self/exe.",
    "set -eu",
    'if [ "$#" -gt 0 ]; then',
    '  count=$#',
    '  i=0',
    '  while [ "$i" -lt "$count" ]; do',
    '    arg=$1',
    '    shift',
    '    if [ "$arg" != "--process-per-session" ]; then',
    '      set -- "$@" "$arg"',
    '    fi',
    '    i=$((i + 1))',
    '  done',
    'fi',
    `exec ${shellQuote(targetCommand)} "$@"`,
    "",
  ].join("\n");
}

/**
 * Returns the executable path OAR should invoke for Antigravity ACP operations.
 * Native ELF / macOS / Windows binaries are returned unchanged. A Linux glibc
 * loader wrapper script is wrapped in a tiny private shim that drops
 * `--process-per-session`, preserving the user's native `~/.gemini` config,
 * skills, plugins, and login.
 */
export function resolveAntigravityAcpCommand(
  command: string,
  options: {
    platform?: NodeJS.Platform;
    shimDir?: string;
  } = {},
): string {
  const platform = options.platform ?? process.platform;
  if (!isGlibcLoaderWrapperScript(command, platform)) return command;
  const resolved = path.resolve(command);
  const digest = createHash("sha256").update(resolved).digest("hex").slice(0, 12);
  const baseDir = options.shimDir ?? (() => {
    try {
      return path.join(resolveRaftHome(), "runtime-shims");
    } catch {
      return path.join(os.tmpdir(), "raft-runtime-shims");
    }
  })();
  const shimPath = path.join(baseDir, `antigravity-acp-${digest}.sh`);
  const content = buildAcpShimScript(resolved);
  try {
    mkdirSync(baseDir, { recursive: true, mode: 0o700 });
    const tmpPath = `${shimPath}.${process.pid}.${Date.now()}.tmp`;
    writeFileSync(tmpPath, content, { mode: 0o700 });
    chmodSync(tmpPath, 0o700);
    renameSync(tmpPath, shimPath);
    return shimPath;
  } catch {
    return existsSync(shimPath) ? shimPath : command;
  }
}
